let step = 0;
let choices = [];
let resultIndex = 0;
const $ = id => document.getElementById(id);
function show(view) { ['intro', 'quiz', 'result'].forEach(id => $(id).hidden = id !== view); }
function render() {
  show('quiz');
  const [title, hint, answers] = questions[step];
  $('question').textContent = title;
  $('hint').textContent = hint;
  $('count').textContent = `${step + 1} / ${questions.length}`;
  $('bar').style.width = `${(step + 1) / questions.length * 100}%`;
  $('back').hidden = step === 0;
  $('answers').replaceChildren();
  answers.forEach((answer, index) => {
    const button = document.createElement('button');
    button.className = 'answer';
    const letter = document.createElement('span');
    letter.className = 'letter'; letter.textContent = String.fromCharCode(65 + index);
    const label = document.createElement('span'); label.textContent = answer;
    button.append(letter, label);
    button.onclick = () => { choices[step] = index; choices.length = step + 1; step++; step < questions.length ? render() : finish(); };
    $('answers').append(button);
  });
  $('question').focus();
}
function finish() {
  const scores = [0, 0, 0, 0]; choices.forEach(index => scores[index]++);
  resultIndex = scores.indexOf(Math.max(...scores));
  $('result-title').textContent = results[resultIndex][0];
  $('result-text').textContent = results[resultIndex][1];
  $('share-status').textContent = '';
  show('result'); $('result-title').focus();
}
$('start').onclick = $('restart').onclick = () => { step = 0; choices = []; render(); };
$('back').onclick = () => { if (step > 0) { step--; render(); } };
$('share').onclick = async () => {
  const text = `В Братстве Тахира я — ${results[resultIndex][0]}! ${results[resultIndex][1]}`;
  try { await navigator.clipboard.writeText(text); $('share-status').textContent = 'Результат скопирован. Можно отправить Братству!'; }
  catch { $('share-status').textContent = 'Копирование недоступно. Выдели и скопируй текст результата вручную.'; }
};
